def main():
    os.makedirs(BACKUP_DIR, exist_ok=True)
    ts = datetime.now().strftime("%Y%m%d_%H%M%S")
    backup_path = os.path.join(BACKUP_DIR, f"religious_strict_rules_script_backup_{ts}.json")

    conn = sqlite3.connect(DB_PATH)
    conn.row_factory = sqlite3.Row
    cur = conn.cursor()
    existing = [dict(r) for r in cur.execute(
        "SELECT * FROM strict_qa_rules WHERE department='Religious' ORDER BY updated_at DESC"
    )]
    with open(backup_path, "w", encoding="utf-8") as f:
        json.dump(existing, f, ensure_ascii=False, indent=2)
    cur.execute("DELETE FROM strict_qa_rules WHERE department='Religious'")
    conn.commit()
    conn.close()

    kb = KnowledgeBase(DB_PATH)
    created = []
    for item in RULES:
        res = kb.add_strict_qa_rule(
            item["question"],
            item["answer"],
            department="Religious",
            match_type=item["match_type"],
            is_enabled=True,
        )
        created.append(
            {
                "question": item["question"],
                "match_type": item["match_type"],
                "status": res.get("status"),
                "rule_id": res.get("rule_id"),
            }
        )

    conn = sqlite3.connect(DB_PATH)
    cur = conn.cursor()
    count = cur.execute(
        "SELECT COUNT(*) FROM strict_qa_rules WHERE department='Religious'"
    ).fetchone()[0]
    conn.close()

    print(
        json.dumps(
            {
                "backup_path": backup_path,
                "created_count": len(created),
                "religious_rules_after": count,
            },
            ensure_ascii=False,
            indent=2,
        )
    )


if __name__ == "__main__":
    main()
